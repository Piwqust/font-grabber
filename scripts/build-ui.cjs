// Builds both surfaces from one component library.
//
//   npm run build:ui        one-off build
//   npm run build:ui -- -w  rebuild on change (design iteration)
//
// Outputs:
//   core/src/web/assets/app.js   website bundle, embedded in the Rust binary
//   core/src/web/style.css       website stylesheet, embedded in the binary
//   extension/popup.bundle.js    popup bundle
//   extension/popup.css          popup stylesheet
//
// The stylesheets are concatenations: both start with the shared tokens and
// components, and differ only in the @font-face paths and their own layout.
const { build, context } = require("esbuild");
const fs = require("node:fs");
const path = require("node:path");

const watch = process.argv.includes("-w") || process.argv.includes("--watch");

const shared = {
  bundle: true,
  minify: !watch,
  sourcemap: watch ? "inline" : false,
  format: "iife",
  target: ["es2022"],
  jsx: "automatic",
  jsxImportSource: "preact",
  legalComments: "linked",
  logLevel: "info",
};

const TARGETS = [
  {
    ...shared,
    entryPoints: ["core/src/web/src/main.jsx"],
    outfile: "core/src/web/assets/app.js",
  },
  {
    ...shared,
    entryPoints: ["extension/src/popup.jsx"],
    outfile: "extension/popup.bundle.js",
  },
];

const STYLES = [
  {
    out: "core/src/web/style.css",
    parts: [
      "node_modules/open-props/shadows.min.css",
      "node_modules/open-props/borders.min.css",
      "node_modules/open-props/easings.min.css",
      "core/src/web/styles/fonts-web.css",
      "core/src/web/styles/base.css",
      "core/src/web/styles/components.css",
      "core/src/web/styles/site.css",
      "core/src/web/styles/auth.css",
    ],
  },
  {
    out: "extension/popup.css",
    parts: [
      "core/src/web/styles/fonts-ext.css",
      "core/src/web/styles/base.css",
      "core/src/web/styles/components.css",
      "extension/popup.src.css",
    ],
  },
];

const BANNER =
  "/* Generated by `npm run build:ui`. Edit the sources listed below, not this file. */\n";

function buildStyles() {
  for (const style of STYLES) {
    const body = style.parts
      .map(
        (part) =>
          `/* ---------- ${part} ---------- */\n${fs.readFileSync(part, "utf8").trim()}\n`,
      )
      .join("\n");
    fs.writeFileSync(style.out, `${BANNER}\n${body}`);
    console.log(
      `  ${style.out}  ${(fs.statSync(style.out).size / 1024).toFixed(1)}kb`,
    );
  }
}

const LICENSED = [
  "preact",
  "motion",
  "motion-dom",
  "motion-utils",
  "@floating-ui/dom",
  "@floating-ui/core",
  "@floating-ui/utils",
];

function writeNotices() {
  let notice = "Bundled UI dependencies. Built using npm run build:ui.\n\n";
  for (const name of LICENSED) {
    const folder = path.join("node_modules", name);
    if (!fs.existsSync(folder)) continue;
    const meta = JSON.parse(
      fs.readFileSync(path.join(folder, "package.json"), "utf8"),
    );
    const file = ["LICENSE", "LICENSE.md", "LICENSE.txt"].find((f) =>
      fs.existsSync(path.join(folder, f)),
    );
    notice +=
      `${name} ${meta.version} (${meta.license})\n` +
      (file
        ? fs.readFileSync(path.join(folder, file), "utf8")
        : "See package license metadata.") +
      "\n\n";
  }
  fs.writeFileSync("core/src/web/assets/ui-LICENSES.txt", notice);
  fs.copyFileSync(
    "core/src/web/assets/ui-LICENSES.txt",
    "extension/ui-LICENSES.txt",
  );
}

(async () => {
  if (watch) {
    for (const target of TARGETS) {
      const ctx = await context(target);
      await ctx.watch();
    }
    // esbuild watches JS; CSS is cheap enough to poll from here.
    for (const style of STYLES)
      for (const part of style.parts)
        fs.watch(part, () => {
          try {
            buildStyles();
          } catch (error) {
            console.error(error.message);
          }
        });
    buildStyles();
    writeNotices();
    console.log(
      "watching core/src/web/src, core/src/web/styles and extension/src …",
    );
  } else {
    for (const target of TARGETS) await build(target);
    buildStyles();
    writeNotices();
  }
})();
